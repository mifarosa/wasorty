/**
 * Finds which deal of every ready-made level (1 to LEVEL_COUNT) is the solvable one and writes
 * it to src/game/dealTable.js. Opening a level then needs no search for a solvable deal, which
 * took a fraction of a second on a computer and much longer on a slow phone. Run it with
 * `npm run bake` whenever the levels change; a test fails until the table matches again.
 */
import { writeFileSync } from 'node:fs';
import { findLevelDealTicket, LEVEL_COUNT } from '../src/game/levels.js';

const tickets = [];
for (let level = 1; level <= LEVEL_COUNT; level++) tickets.push(findLevelDealTicket(level));

const rows = [];
for (let i = 0; i < tickets.length; i += 8) {
  rows.push(
    `  ${tickets
      .slice(i, i + 8)
      .map((ticket) => `[${ticket.join(', ')}]`)
      .join(', ')}`
  );
}
writeFileSync(
  new URL('../src/game/dealTable.js', import.meta.url),
  `// Generated by scripts/bakeDeals.mjs (npm run bake); do not edit by hand.

/**
 * For levels 1, 2, 3 … in order: [the number of the seed that dealt a solvable puzzle, the number
 * of the deal of that seed]. See dealPuzzle in levels.js.
 */
export const DEAL_TICKETS = Object.freeze([
${rows.join(',\n')}
]);
`
);
console.log(`Wrote the deals of ${tickets.length} levels.`);
